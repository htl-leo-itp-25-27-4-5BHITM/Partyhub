-- Host dashboard: follow and attendance history plus optional profile demographics.
-- Additive only: new tables and nullable columns, no data changes.

CREATE TABLE public.follow_event (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    follower_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    followed_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    type varchar(16) NOT NULL CHECK (type IN ('FOLLOWED', 'UNFOLLOWED')),
    occurred_at timestamp(6) NOT NULL
);
CREATE INDEX follow_event_followed_time_idx ON public.follow_event (followed_id, occurred_at);

CREATE TABLE public.attendance_event (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    party_id bigint NOT NULL REFERENCES public.party(id) ON DELETE CASCADE,
    user_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    type varchar(16) NOT NULL CHECK (type IN ('JOINED', 'LEFT')),
    occurred_at timestamp(6) NOT NULL
);
CREATE INDEX attendance_event_party_time_idx ON public.attendance_event (party_id, occurred_at);

ALTER TABLE public.users ADD COLUMN gender varchar(32)
    CHECK (gender IN ('MALE', 'FEMALE', 'DIVERSE', 'NOT_SPECIFIED'));
ALTER TABLE public.users ADD COLUMN birth_date date;
