-- Settings page (openspec change add-settings-page): account preferences, private/public
-- accounts, blocking and e-mail change requests. Adds tables and columns only; no rows are
-- deleted and no existing values change.

-- Account preferences. A missing row means "never changed", i.e. the defaults apply.
CREATE TABLE public.user_settings (
    user_id bigint PRIMARY KEY REFERENCES public.users(id) ON DELETE CASCADE,
    theme character varying(10) NOT NULL DEFAULT 'SYSTEM',
    updated_at timestamp(6) with time zone NOT NULL DEFAULT now(),
    CONSTRAINT user_settings_theme_check CHECK (theme IN ('LIGHT', 'DARK', 'SYSTEM'))
);

-- Existing accounts become private so their follow-request behaviour stays as it was;
-- accounts created afterwards are public.
ALTER TABLE public.users ADD COLUMN is_private boolean NOT NULL DEFAULT true;
ALTER TABLE public.users ALTER COLUMN is_private SET DEFAULT false;

-- When the e-mail was last changed through a confirmed change. Tokens issued before that
-- still carry the old address and must not overwrite the new one.
ALTER TABLE public.users ADD COLUMN email_changed_at timestamp(6) with time zone;

-- Finer notification preferences. New categories start with the value of the category
-- they were split from, so nobody suddenly receives (or loses) notifications.
ALTER TABLE public.user_notification_settings ADD COLUMN all_enabled boolean NOT NULL DEFAULT true;
ALTER TABLE public.user_notification_settings ADD COLUMN invitation_responses boolean NOT NULL DEFAULT true;
ALTER TABLE public.user_notification_settings ADD COLUMN party_cancellations boolean NOT NULL DEFAULT true;
ALTER TABLE public.user_notification_settings ADD COLUMN unfollows boolean NOT NULL DEFAULT true;
UPDATE public.user_notification_settings
   SET invitation_responses = party_invites,
       party_cancellations = party_updates,
       unfollows = follow_events;

-- blocker_id blocks blocked_id; the effects apply in both directions.
CREATE TABLE public.user_block (
    blocker_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    blocked_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    created_at timestamp(6) with time zone NOT NULL DEFAULT now(),
    PRIMARY KEY (blocker_id, blocked_id),
    CONSTRAINT user_block_not_self CHECK (blocker_id <> blocked_id)
);
CREATE INDEX user_block_blocked_idx ON public.user_block (blocked_id);

-- At most one pending e-mail change per user. Only SHA-256 hashes of the link tokens are stored.
CREATE TABLE public.email_change_request (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL UNIQUE REFERENCES public.users(id) ON DELETE CASCADE,
    new_email character varying(254) NOT NULL,
    confirm_token_hash character varying(64) NOT NULL UNIQUE,
    cancel_token_hash character varying(64) NOT NULL UNIQUE,
    created_at timestamp(6) with time zone NOT NULL,
    expires_at timestamp(6) with time zone NOT NULL,
    user_agent character varying(255)
);

-- Request/resend attempts for the rate limit (5 per user and hour).
CREATE TABLE public.email_change_attempt (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    attempted_at timestamp(6) with time zone NOT NULL
);
CREATE INDEX email_change_attempt_user_idx ON public.email_change_attempt (user_id, attempted_at);
