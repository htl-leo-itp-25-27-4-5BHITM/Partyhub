CREATE TABLE public.bring_along_item (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    party_id bigint NOT NULL REFERENCES public.party(id) ON DELETE CASCADE,
    name varchar(100) NOT NULL,
    unit varchar(30),
    quantity integer NOT NULL CHECK (quantity BETWEEN 1 AND 10000),
    created_at timestamp(6) NOT NULL
);
CREATE INDEX bring_along_item_party_idx ON public.bring_along_item (party_id);

CREATE TABLE public.bring_along_pledge (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id bigint NOT NULL REFERENCES public.bring_along_item(id) ON DELETE CASCADE,
    user_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    quantity integer NOT NULL CHECK (quantity >= 1),
    CONSTRAINT bring_along_pledge_item_user_unique UNIQUE (item_id, user_id)
);
CREATE INDEX bring_along_pledge_user_idx ON public.bring_along_pledge (user_id);
